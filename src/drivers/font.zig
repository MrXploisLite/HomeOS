/// Optimized character drawing - batch pixels per row
pub fn drawChar(x: i32, y: i32, char: u8, fg: Color, bg: ?Color) void {
    if (char < 32 or char > 126) return;
    if (x < -8 or y < -8) return; // Early bounds check

    const glyph = font_data[char - 32];
    const fg_val = fg.toU32();
    const has_bg = bg != null;
    const bg_val = if (bg) |b| b.toU32() else 0;

    // Get direct buffer access for speed
    const buffer = graphics.getDrawBufferDirect();
    const screen_w = graphics.getWidth();
    const screen_h = graphics.getHeight();

    var row: u32 = 0;
    while (row < FONT_HEIGHT) : (row += 1) {
        const py = y + @as(i32, @intCast(row));
        if (py < 0 or py >= @as(i32, @intCast(screen_h))) {
            continue;
        }

        const row_data = glyph[row];
        const base_offset = @as(u32, @intCast(py)) * screen_w;

        var col: u32 = 0;
        while (col < FONT_WIDTH) : (col += 1) {
            const px = x + @as(i32, @intCast(col));
            if (px < 0 or px >= @as(i32, @intCast(screen_w))) {
                continue;
            }

            const bit = (row_data >> @truncate(7 - col)) & 1;
            const offset = base_offset + @as(u32, @intCast(px));

            if (bit == 1) {
                buffer[offset] = fg_val;
            } else if (has_bg) {
                buffer[offset] = bg_val;
            }
        }
    }
}

/// Optimized string drawing - skip invisible strings
pub fn drawString(x: i32, y: i32, str: []const u8, fg: Color, bg: ?Color) void {
    if (str.len == 0) return;

    // Early bounds check - skip if entirely off screen
    const screen_w = graphics.getWidth();
    const screen_h = graphics.getHeight();
    if (y >= @as(i32, @intCast(screen_h)) or y + 8 < 0) return;
    if (x >= @as(i32, @intCast(screen_w))) return;

    var cx = x;
    for (str) |char| {
        if (char == '\n') continue;
        // Skip chars that are off-screen left
        if (cx + 8 <= 0) {
            cx += @as(i32, FONT_WIDTH);
            continue;
        }
        // Stop if we're past right edge
        if (cx >= @as(i32, @intCast(screen_w))) break;

        drawChar(cx, y, char, fg, bg);
        cx += @as(i32, FONT_WIDTH);
    }
}

pub fn drawStringWrapped(x: i32, y: i32, width: u32, str: []const u8, fg: Color, bg: ?Color) void {
    var cx = x;
    var cy = y;
    const max_x = x + @as(i32, @intCast(width));

    for (str) |char| {
        if (char == '\n') {
            cx = x;
            cy += @as(i32, FONT_HEIGHT);
            continue;
        }

        if (cx + @as(i32, FONT_WIDTH) > max_x) {
            cx = x;
            cy += @as(i32, FONT_HEIGHT);
        }

        drawChar(cx, cy, char, fg, bg);
        cx += @as(i32, FONT_WIDTH);
    }
}

pub fn measureString(str: []const u8) u32 {
    return @truncate(str.len * FONT_WIDTH);
}
